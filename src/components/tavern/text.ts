export type TavernTextKey = keyof typeof labels

export const useTavernText = () => {
  const locale = useSettings((s) => s.locale)
  return (key: TavernTextKey, values: Record<string, string | number> = {}) =>
    Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      labels[key][locale === 'zh-CN' ? 0 : 1] as string
    )
}
